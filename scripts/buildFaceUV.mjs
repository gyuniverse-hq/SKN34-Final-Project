/**
 * Builds components/ar/faceUV.ts from MediaPipe's canonical face model (AR_SPEC 6-4).
 * Source: assets/face/canonical_face_model.obj
 *   https://github.com/google-ai-edge/mediapipe/blob/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj
 *   License: Apache 2.0 (MediaPipe).
 * Run: node scripts/buildFaceUV.mjs
 *
 * The canonical mesh covers the mouth opening and both eyes. Triangles whose three vertices all
 * lie on the inner-lip or an eye contour are dropped so those areas are holes (teeth and eyes are
 * never painted, AR_SPEC 6-4). __tests__/faceMesh.test.ts checks this.
 *
 * The obj uses separate vertex and texture-coordinate indices, so each vertex's UV is taken
 * from the face corners that reference it. UVs are written as-is (no V flip); the AR page
 * paints and samples masks in the same (u, v) space, so no flip is needed anywhere.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const obj = readFileSync(join(root, 'assets/face/canonical_face_model.obj'), 'utf8');

const texcoords = [];
let vertexCount = 0;
const triangles = [];
const uvByVertex = new Map();

for (const line of obj.split(/\r?\n/)) {
  const parts = line.trim().split(/\s+/);
  if (parts[0] === 'v') vertexCount++;
  else if (parts[0] === 'vt') texcoords.push([Number(parts[1]), Number(parts[2])]);
  else if (parts[0] === 'f') {
    if (parts.length !== 4) throw new Error(`non-triangle face: ${line}`);
    for (const corner of parts.slice(1)) {
      const [v, vt] = corner.split('/').map((n) => Number(n) - 1);
      triangles.push(v);
      const uv = texcoords[vt];
      const prev = uvByVertex.get(v);
      if (prev && (prev[0] !== uv[0] || prev[1] !== uv[1])) throw new Error(`vertex ${v} has two UVs`);
      uvByVertex.set(v, uv);
    }
  }
}

// Landmark contours that bound the holes (same indices as the AR page).
const HOLE_CONTOURS = [
  [78, 191, 80, 81, 82, 13, 312, 311, 310, 415, 308, 324, 318, 402, 317, 14, 87, 178, 88, 95],
  [33, 7, 163, 144, 145, 153, 154, 155, 133, 173, 157, 158, 159, 160, 161, 246],
  [263, 249, 390, 373, 374, 380, 381, 382, 362, 398, 384, 385, 386, 387, 388, 466],
];
const holeSets = HOLE_CONTOURS.map((c) => new Set(c));
const kept = [];
const mouth = [];
for (let i = 0; i < triangles.length; i += 3) {
  const tri = triangles.slice(i, i + 3);
  // The mouth hole is kept separately: the AR page draws it only while the lips are closed, so the
  // thin gap between the lips is painted instead of showing a dotted bare-lip line (device 10-23).
  if (tri.every((v) => holeSets[0].has(v))) { mouth.push(...tri); continue; }
  if (holeSets.some((set) => tri.every((v) => set.has(v)))) continue;
  kept.push(...tri);
}

if (vertexCount !== 468) throw new Error(`expected 468 vertices, got ${vertexCount}`);
const uv = [];
for (let i = 0; i < vertexCount; i++) {
  const t = uvByVertex.get(i);
  if (!t) throw new Error(`vertex ${i} has no UV`);
  uv.push(Number(t[0].toFixed(5)), Number(t[1].toFixed(5)));
}

const out = `// Generated by scripts/buildFaceUV.mjs from MediaPipe canonical_face_model.obj (Apache 2.0). Do not edit.
// FACE_UV: 468 × (u, v). FACE_TRIANGLES: ${kept.length / 3} triangles (mouth and eye holes removed).
export const FACE_UV: number[] = ${JSON.stringify(uv)};

export const FACE_TRIANGLES: number[] = ${JSON.stringify(kept)};

// Mouth-hole triangles (all three vertices on the inner lip line): drawn only while the mouth is closed.
export const FACE_MOUTH_TRIANGLES: number[] = ${JSON.stringify(mouth)};
`;
writeFileSync(join(root, 'components/ar/faceUV.ts'), out);
console.log(`faceUV.ts: ${vertexCount} vertices, ${kept.length / 3} of ${triangles.length / 3} triangles kept`);
