// Development-only screen recorder for the AR page (AR_SPEC 1-4, 11-02 exception: evaluation clips).
//
// The AR page itself never records or saves (1-4, faceTracker.test.ts). In development the app injects this script into
// the running page when the user taps the record button; a production page has no recorder code at all. The script
// records the page's WebGL canvas (the camera image with the makeup on it; the guide overlay and HUD are separate canvases
// and are not in it) with MediaRecorder, no audio, and hands the pieces to the app over the existing bridge as base64.
// The app writes them to a file on this device only. Nothing here touches the network or browser storage.
//
// Messages to the app: rec_state { state: 'recording', mime }, rec_chunk { n, data }, rec_done { mime, bytes, chunks, ms },
// rec_error { detail }. Controls: window.__kbRec.start() / .stop().
export const AR_RECORDER_SCRIPT = [
  '(function () {',
  '  if (window.__kbRec) return;',
  '  var MAX_MS = 60000, SLICE_MS = 1000, FPS = 30, BITS = 4000000, STEP = 196608;',
  '  var rec = null, stream = null, timer = 0, started = 0, bytes = 0, seq = 0, mime = "", queue = Promise.resolve();',
  '  function post(m) { if (window.ReactNativeWebView) window.ReactNativeWebView.postMessage(JSON.stringify(m)); }',
  '  function fail(detail) { cleanup(); post({ type: "rec_error", detail: detail }); }',
  '  function cleanup() {',
  '    clearTimeout(timer);',
  '    if (stream) stream.getTracks().forEach(function (t) { t.stop(); });',
  '    rec = null; stream = null;',
  '  }',
  '  function pickMime() {',
  '    var list = ["video/mp4;codecs=avc1", "video/mp4", "video/webm;codecs=vp9", "video/webm;codecs=vp8", "video/webm"];',
  '    for (var i = 0; i < list.length; i++) if (MediaRecorder.isTypeSupported(list[i])) return list[i];',
  '    return "";',
  '  }',
  '  function b64(buf) {',
  '    var a = new Uint8Array(buf), bin = "";',
  '    for (var i = 0; i < a.length; i += 32768) bin += String.fromCharCode.apply(null, a.subarray(i, i + 32768));',
  '    return btoa(bin);',
  '  }',
  '  function stop() {',
  '    clearTimeout(timer);',
  '    if (rec && rec.state !== "inactive") rec.stop();',
  '  }',
  '  function start() {',
  '    if (rec) return;',
  '    var canvas = document.getElementById("canvas");',
  '    if (!canvas || !canvas.captureStream || typeof MediaRecorder === "undefined") return fail("unsupported");',
  '    mime = pickMime(); bytes = 0; seq = 0; queue = Promise.resolve();',
  '    var recorder;',
  '    try {',
  '      stream = canvas.captureStream(FPS);',
  '      recorder = new MediaRecorder(stream, mime ? { mimeType: mime, videoBitsPerSecond: BITS } : { videoBitsPerSecond: BITS });',
  '    } catch (e) { return fail("start: " + (e && e.message)); }',
  '    rec = recorder;',
  '    recorder.ondataavailable = function (ev) {',
  '      var blob = ev.data;',
  '      if (!blob || !blob.size) return;',
  // One chunk at a time, in order; each piece is a complete base64 string, so the app appends the decoded bytes.
  '      queue = queue.then(function () { return blob.arrayBuffer(); }).then(function (buf) {',
  '        for (var o = 0; o < buf.byteLength; o += STEP) post({ type: "rec_chunk", n: seq++, data: b64(buf.slice(o, o + STEP)) });',
  '        bytes += buf.byteLength;',
  '      });',
  '    };',
  '    recorder.onerror = function (ev) { fail("recorder: " + (ev && ev.error && ev.error.name)); };',
  '    recorder.onstop = function () {',
  '      var type = recorder.mimeType || mime;',
  '      queue.then(function () {',
  '        post({ type: "rec_done", mime: type, bytes: bytes, chunks: seq, ms: Date.now() - started });',
  '        cleanup();',
  '      });',
  '    };',
  '    recorder.start(SLICE_MS);',
  '    started = Date.now();',
  '    timer = setTimeout(stop, MAX_MS);',
  '    post({ type: "rec_state", state: "recording", mime: recorder.mimeType || mime });',
  '  }',
  '  window.__kbRec = { start: start, stop: stop };',
  '})();',
  'true;',
].join('\n');
