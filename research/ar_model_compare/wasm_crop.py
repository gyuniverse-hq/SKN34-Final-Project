"""Measure BiSeNet crop tensors with ONNX Runtime Web WASM in local headless Chrome.

Input: tensors generated by hybrid_crop.py, local ONNX and installed onnxruntime-web.
Output: research/data/ar_model_compare/a/hybrid_wasm/metrics.csv and aggregate JSON.
Run: research/ar_evaluation/.venv/Scripts/python.exe research/ar_model_compare/wasm_crop.py
Only intercepted localhost requests are fulfilled; all other network requests are aborted.
"""
import csv
import hashlib
import json
import statistics
from pathlib import Path
from urllib.parse import urlparse

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "research/data/ar_model_compare/a"
INPUTS = DATA / "hybrid_cpu"
OUT = DATA / "hybrid_wasm"
DIST = ROOT / "node_modules/onnxruntime-web/dist"
MODEL = ROOT / "research/bisenet_cuda/models/bisenet-resnet18.onnx"
CHROME = r"C:\Program Files\Google\Chrome\Application\chrome.exe"
EXPECTED = "0d9bd318e46987c3bdbfacae9e2c0f461cae1c6ac6ea6d43bbe541a91727e33f"


def main():
    if hashlib.sha256(MODEL.read_bytes()).hexdigest() != EXPECTED:
        raise RuntimeError("unexpected model hash")
    metrics_path = INPUTS / "metrics.csv"
    if not metrics_path.exists():
        raise SystemExit("Run hybrid_crop.py first")
    with metrics_path.open(encoding="utf-8", newline="") as f:
        files = [INPUTS / f"{row['id']}__{row['sampling_px']}.f32" for row in csv.DictReader(f)]
    if any(not f.is_file() or f.parent != INPUTS for f in files):
        raise RuntimeError("missing or invalid input tensor")
    if not files:
        raise SystemExit("Run hybrid_crop.py first")
    OUT.mkdir(parents=True, exist_ok=True)
    model_bytes = MODEL.read_bytes()
    html = b'<!doctype html><script src="/assets/ort.min.js"></script>'
    allowed_inputs = {f.name: f for f in files}

    def route(request):
        url = urlparse(request.request.url)
        if url.scheme != "http" or url.netloc != "localhost":
            request.abort(); return
        if url.path == "/":
            request.fulfill(status=200, content_type="text/html", body=html); return
        if url.path == "/model.onnx":
            request.fulfill(status=200, content_type="application/octet-stream", body=model_bytes); return
        if url.path.startswith("/inputs/"):
            name = url.path.removeprefix("/inputs/")
            if name in allowed_inputs:
                request.fulfill(status=200, content_type="application/octet-stream", body=allowed_inputs[name].read_bytes()); return
        if url.path.startswith("/assets/"):
            name = url.path.removeprefix("/assets/")
            if name == Path(name).name and name.startswith("ort") and (DIST / name).is_file():
                mime = "application/wasm" if name.endswith(".wasm") else "text/javascript"
                request.fulfill(status=200, content_type=mime, body=(DIST / name).read_bytes()); return
        request.abort()

    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(executable_path=CHROME, headless=True)
        browser_version = browser.version
        context = browser.new_context(); context.route("**/*", route)
        page = context.new_page(); page.goto("http://localhost/")
        version = page.evaluate("ort.env.versions.web")
        rows = page.evaluate("""async names => {
          ort.env.wasm.numThreads = 1;
          ort.env.wasm.wasmPaths = 'http://localhost/assets/';
          const bytes = await (await fetch('/model.onnx')).arrayBuffer();
          const session = await ort.InferenceSession.create(bytes, { executionProviders: ['wasm'] });
          const rows = [];
          for (const name of names) {
            const data = new Float32Array(await (await fetch('/inputs/' + name)).arrayBuffer());
            const input = new ort.Tensor('float32', data, [1,3,512,512]);
            await session.run({[session.inputNames[0]]: input});
            const t = performance.now();
            const output = await session.run({[session.inputNames[0]]: input});
            const ms = performance.now() - t;
            const dimensions = output[session.outputNames[0]].dims;
            rows.push({ file: name, inference_ms: ms, output_shape: dimensions.join('x') });
          }
          await session.release();
          return rows;
        }""", [f.name for f in files])
        browser.close()
    with (OUT / "metrics.csv").open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=("file", "inference_ms", "output_shape")); writer.writeheader(); writer.writerows(rows)
    with metrics_path.open(encoding="utf-8", newline="") as f:
        cpu_rows = list(csv.DictReader(f))
    summary = {"status": "timing_only_no_ground_truth", "model_sha256": EXPECTED,
               "browser_version": browser_version, "onnxruntime_web": version, "threads": 1,
               "note": "desktop headless Chrome WASM; inference only; sampled crops are resized to fixed 512 model input; not phone performance",
               "cpu_source": "research/data/ar_model_compare/a/hybrid_cpu/metrics.csv",
               "wasm_source": "research/data/ar_model_compare/a/hybrid_wasm/metrics.csv", "resolutions": {}}
    print(f"onnxruntime-web {version}; WASM single-thread; {len(rows)} runs")
    for size in (128, 192, 256):
        vals = sorted(row["inference_ms"] for row in rows if row["file"].endswith(f"__{size}.f32"))
        cpu = [float(row["inference_ms"]) for row in cpu_rows if int(row["sampling_px"]) == size]
        summary["resolutions"][str(size)] = {"n": len(vals), "wasm_ms_median": statistics.median(vals),
                                             "cpu_ms_median": statistics.median(cpu), "iou": None, "boundary_px": None}
        print(f"{size}: median {statistics.median(vals):.1f} ms (n={len(vals)}); network input 512")
    result = ROOT / "research/ar_model_compare/results/hybrid_summary.json"
    result.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(OUT / "metrics.csv")


if __name__ == "__main__":
    main()
